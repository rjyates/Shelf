pub fn additional_suppressions(lang: &str) -> &'static [&'static str] {
    match lang {
        "en" => &["TL;DR"],
        "th" => &["ค.ศ."],
        _ => &[],
    }
}

pub fn contraction_suppressions(lang: &str) -> &'static [&'static str] {
    match lang {
        "en" => &["'cause", "'til", "'bout", "'twas", "'tis"],
        "af" => &["'n"],
        _ => &[],
    }
}

pub const NOUN_SUPPRESSIONS: &[&str] = &[
    "C#",
    "F#",
    "C++",
    "Yahoo!",
    "Toys\"R\"Us",
    "Dunkin'",
    "Ke$ha",
    "I/O",
    "Sky+",
    "A/C",
    "A/V",
];

pub const TLD_SUPPRESSIONS: &[&str] = &[".com", ".org", ".net", ".co", ".us"];

/// Locale + shared noun/TLD suppressions, longest-first (Echogarden splitter).
pub fn word_suppressions(lang: &str) -> Vec<String> {
    let mut out: Vec<String> = cldr_suppressions(lang)
        .iter()
        .chain(additional_suppressions(lang).iter())
        .chain(contraction_suppressions(lang).iter())
        .chain(NOUN_SUPPRESSIONS.iter())
        .chain(TLD_SUPPRESSIONS.iter())
        .flat_map(|s| {
            let lower = s.to_lowercase();
            let upper = s.to_uppercase();
            let mut v = vec![(*s).to_string()];
            if lower != *s {
                v.push(lower.clone());
            }
            if upper != *s && upper != lower {
                v.push(upper);
            }
            v
        })
        .collect();
    out.sort_by_key(|s| std::cmp::Reverse(s.len()));
    out.dedup();
    out
}
